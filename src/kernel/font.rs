/// Les 5 colonnes du glyphe de `c` (un `?` pour ce qui n'est pas de l'ASCII imprimable).
fn glyph(c: u8) -> &'static [u8; 5] {
    let index = if (32..127).contains(&c) {
        c - 32
    } else {
        b'?' - 32
    };
    &GLYPHS[usize::from(index)]
}

/// Appelle `plot(x, y)` pour chaque pixel allumé du caractère `c`, dans sa cellule (le coin
/// haut-gauche est `(0, 0)`).
///
/// En petit, la matrice est étirée en hauteur ×2 sur ses 7 premières lignes (une colonne de pixels par
/// colonne de la matrice, décalée d'un pixel vers la droite) ; en grand, elle est étirée ×2
/// dans les deux sens. La huitième ligne de la matrice (queue des `g`, `j`, `p`, `q`, `y`) n'est
/// dessinée qu'en grand.
pub fn draw_glyph(c: u8, large: bool, mut plot: impl FnMut(u32, u32)) {
    let columns = glyph(c);
    let (scale_x, rows, top, left) = if large { (2, 8, 1, 0) } else { (1, 7, 0, 1) };
    for (cx, &bits) in columns.iter().enumerate() {
        for row in 0..rows {
            if bits >> row & 1 == 0 {
                continue;
            }
            for dy in 0..2 {
                for dx in 0..scale_x {
                    let x = cx as u32 * scale_x + dx + left;
                    plot(x, top + row * 2 + dy);
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn lit(c: u8, large: bool) -> Vec<(u32, u32)> {
        let mut points = Vec::new();
        draw_glyph(c, large, |x, y| points.push((x, y)));
        points
    }

    #[test]
    fn space_draws_nothing() {
        assert!(lit(b' ', false).is_empty());
        assert!(lit(b' ', true).is_empty());
    }

    #[test]
    fn pixels_stay_inside_the_cell() {
        for c in 0..=255u8 {
            for (large, cell) in [(false, SMALL), (true, LARGE)] {
                for (x, y) in lit(c, large) {
                    assert!(x < cell.width && y < cell.height, "{c} {large} {x},{y}");
                }
            }
        }
    }

    #[test]
    fn unknown_characters_look_like_a_question_mark() {
        assert_eq!(lit(0x01, false), lit(b'?', false));
        assert_eq!(lit(0xe9, true), lit(b'?', true));
    }

    #[test]
    fn letters_differ() {
        assert_ne!(lit(b'a', false), lit(b'b', false));
        assert_ne!(lit(b'A', true), lit(b'V', true));
    }
}
